// Great-circle Haversine formula
export function haversineDistanceMeters(lat1, lon1, lat2, lon2) {
  const rad = x => (x * Math.PI) / 180;
  const dLat = rad(lat2 - lat1);
  const dLon = rad(lon2 - lon1);
  const a =
    Math.sin(dLat / 2) * Math.sin(dLat / 2) +
    Math.cos(rad(lat1)) * Math.cos(rad(lat2)) * Math.sin(dLon / 2) * Math.sin(dLon / 2);
  const c = 2 * Math.atan2(Math.sqrt(a), Math.sqrt(1 - a));
  return 6371000 * c;
}

// Locate nearest MRT station with street-winding factor and standard walking pace (~80m/min)
export function findNearestMrtStation(originLat, originLng) {
  const lat = Number(originLat);
  const lng = Number(originLng);
  if (!Number.isFinite(lat) || !Number.isFinite(lng) || lat < 20 || lat > 27 || lng < 118 || lng > 123) {
    return null;
  }

  let nearest = null;
  let minStraight = Infinity;

  for (const station of TAIWAN_MRT_STATIONS) {
    const straight = haversineDistanceMeters(lat, lng, station.lat, station.lng);
    if (straight < minStraight) {
      minStraight = straight;
      nearest = station;
    }
  }

  if (!nearest) return null;

  // Urban pedestrian factor in Taiwan street grids: 1.25x to 1.3x straight distance
  const streetDistanceMeters = Math.round(minStraight * 1.25);
  // Average walking pace: ~75-80 meters per minute (4.5 - 4.8 km/h)
  const walkMinutes = Math.max(1, Math.round(streetDistanceMeters / 78));

  return {
    station: nearest.name,
    line: nearest.line,
    stationGeo: { lat: nearest.lat, lng: nearest.lng },
    straightDistanceMeters: Math.round(minStraight),
    walkDistanceMeters: streetDistanceMeters,
    walkMinutes,
    isWithin10Min: walkMinutes <= 10,
    directionsUrl: `https://www.google.com/maps/dir/?api=1&origin=${lat.toFixed(6)},${lng.toFixed(6)}&destination=${nearest.lat.toFixed(6)},${nearest.lng.toFixed(6)}&travelmode=walking`
  };
}
